`timescale 1ns / 1ps
// EXPERIMENTAL control-plane CDC for V4. NOT AN AXI/AXI-LITE SLAVE.
// EXPERIMENTAL per-domain synchronous local resets, no shared async reset.
// ps_resetn and adc_resetn come from Phase4A reset release flops.
 // AXI controller's frontend_online MUST be gated by synchronized ADC-ready.
// Requests are single PS-clock pulses. Inputs are ignored while busy.
// Payload bus crossing is coherent by a toggle + held-data handshake:
// the transmitting domain holds each bus unchanged until a synchronized
// response returns; the receiving domain samples only after sync delay.
// For standalone XSim validation BEFORE attaching any PS AXI register slave.
module v4_frame_mailbox_cdc_domains_experimental (
    input wire         ps_clk,
    input wire         adc_clk,
    input wire         ps_resetn,
    input wire         adc_resetn,

    // PS-domain snapshot request and latched coherent result.
    input wire         ps_status_req,
    output reg         ps_status_busy,
    output reg         ps_status_valid, // 1-cycle pulse, data registers persist
    output reg [1:0]   ps_frame_ready,
    output reg [31:0]  ps_bank0_sequence,
    output reg [31:0]  ps_bank1_sequence,
    output reg [31:0]  ps_completed_frames,
    output reg [31:0]  ps_captures_started,
    output reg [31:0]  ps_captures_replayed,
    output reg [31:0]  ps_skipped_windows,
    output reg         ps_scheduler_idle,

    input wire         ps_capture_req,
    input wire         ps_capture_enable,
    input wire [31:0]  ps_capture_period,
    output reg         ps_capture_busy,
    output reg         ps_capture_done,
    output reg         ps_capture_accepted,

    output reg         ps_active_run,
    output reg [31:0]  ps_active_period,

    output reg         adc_run_enable,
    output reg [31:0]  adc_period_cycles,

    // PS-domain ACK transaction: bank AND expected sequence MUST match.
    input wire         ps_ack_req,
    input wire         ps_ack_bank,
    input wire [31:0]  ps_ack_expected_sequence,
    output reg         ps_ack_busy,
    output reg         ps_ack_done,  // 1-cycle pulse, accepted register persists
    output reg         ps_ack_accepted,

    // ADC domain connection to the original v3 ping-pong frame sink.
    input wire [1:0]   adc_frame_ready,
    input wire [31:0]  adc_bank0_sequence,
    input wire [31:0]  adc_bank1_sequence,
    input wire [31:0]  adc_completed_frames,
    input wire [31:0]  adc_captures_started,
    input wire [31:0]  adc_captures_replayed,
    input wire [31:0]  adc_skipped_windows,
    input wire         adc_scheduler_idle,
    output reg         adc_sw_ack_valid,
    output reg         adc_sw_ack_bank
);
    // Phase 4B experiment: two REGISTERED local reset-release inputs.
    // NO combinational frontend_ready/PS reset enters any async CLEAR.
    // This mailbox intentionally contains no internal reset release pipes.
    // Both control reset inputs must be generated by clock-domain-local FFs.
    // The PS-visible frontend online indication must additionally synchronize
    // ADC reset-release and prevent requests until the ADC domain is ready.

    // PS -> ADC: request toggles and held request payload.
    reg status_req_toggle;
    reg ack_req_toggle;
    reg ack_bank_held;
    reg [31:0] ack_seq_held;

    // ADC -> PS: coherent response bundles held until next request.
    reg status_reply_toggle;
    reg [1:0]  status_ready_held;
    reg [31:0] status_seq0_held, status_seq1_held;
    reg [31:0] status_count_held;
    reg [31:0] status_started_held;
    reg [31:0] status_replayed_held;
    reg [31:0] status_skipped_held;
    reg status_idle_held;
    reg status_run_held;
    reg [31:0] status_period_held;
    reg ack_reply_toggle;
    reg ack_result_held;

    // Explicit CDC synchronization of control toggles only.
    (* ASYNC_REG = "TRUE", SHREG_EXTRACT = "NO" *) reg status_req_meta, status_req_sync;
    (* ASYNC_REG = "TRUE", SHREG_EXTRACT = "NO" *) reg ack_req_meta, ack_req_sync;
    (* ASYNC_REG = "TRUE", SHREG_EXTRACT = "NO" *) reg status_reply_meta, status_reply_sync;
    (* ASYNC_REG = "TRUE", SHREG_EXTRACT = "NO" *) reg ack_reply_meta, ack_reply_sync;

    reg status_req_seen, ack_req_seen;
    reg status_reply_seen, ack_reply_seen;
    reg [1:0] status_ps_settle, ack_ps_settle;
    reg adc_ack_finalize;

    // PS domain: accept new request only if matching transaction idle.
    // Extra settle cycles after synchronized reply before sampling wide bus.
    always @(posedge ps_clk) begin
        if (!ps_resetn) begin
            status_reply_meta <= 1'b0;
            status_reply_sync <= 1'b0;
            ack_reply_meta <= 1'b0;
            ack_reply_sync <= 1'b0;
            status_req_toggle <= 1'b0;
            ack_req_toggle <= 1'b0;
            ack_bank_held <= 1'b0;
            ack_seq_held <= 32'd0;
            status_reply_seen <= 1'b0;
            ack_reply_seen <= 1'b0;
            status_ps_settle <= 2'd0;
            ack_ps_settle <= 2'd0;
            ps_status_busy <= 1'b0;
            ps_status_valid <= 1'b0;
            ps_frame_ready <= 2'b00;
            ps_bank0_sequence <= 32'd0;
            ps_bank1_sequence <= 32'd0;
            ps_completed_frames <= 32'd0;
            ps_captures_started <= 32'd0;
            ps_captures_replayed <= 32'd0;
            ps_skipped_windows <= 32'd0;
            ps_scheduler_idle <= 1'b0;
            ps_active_run <= 1'b0;
            ps_active_period <= 32'd0;
            ps_ack_busy <= 1'b0;
            ps_ack_done <= 1'b0;
            ps_ack_accepted <= 1'b0;
        end else begin
            status_reply_meta <= status_reply_toggle;
            status_reply_sync <= status_reply_meta;
            ack_reply_meta <= ack_reply_toggle;
            ack_reply_sync <= ack_reply_meta;
            ps_status_valid <= 1'b0;
            ps_ack_done <= 1'b0;

            if (!ps_status_busy) begin
                if (ps_status_req) begin
                    status_req_toggle <= ~status_req_toggle;
                    ps_status_busy <= 1'b1;
                end
            end else if (status_ps_settle != 0) begin
                status_ps_settle <= status_ps_settle - 1'b1;
                if (status_ps_settle == 1) begin
                    // ADC holds the complete snapshot stable until new request.
                    ps_frame_ready <= status_ready_held;
                    ps_bank0_sequence <= status_seq0_held;
                    ps_bank1_sequence <= status_seq1_held;
                    ps_completed_frames <= status_count_held;
                    ps_captures_started <= status_started_held;
                    ps_captures_replayed <= status_replayed_held;
                    ps_skipped_windows <= status_skipped_held;
                    ps_scheduler_idle <= status_idle_held;
                    ps_active_run <= status_run_held;
                    ps_active_period <= status_period_held;
                    ps_status_busy <= 1'b0;
                    ps_status_valid <= 1'b1;
                end
            end else if (status_reply_sync != status_reply_seen) begin
                status_reply_seen <= status_reply_sync;
                status_ps_settle <= 2'd2;
            end

            if (!ps_ack_busy) begin
                if (ps_ack_req) begin
                    ack_bank_held <= ps_ack_bank;
                    ack_seq_held <= ps_ack_expected_sequence;
                    ack_req_toggle <= ~ack_req_toggle;
                    ps_ack_busy <= 1'b1;
                end
            end else if (ack_ps_settle != 0) begin
                ack_ps_settle <= ack_ps_settle - 1'b1;
                if (ack_ps_settle == 1) begin
                    ps_ack_accepted <= ack_result_held;
                    ps_ack_done <= 1'b1;
                    ps_ack_busy <= 1'b0;
                end
            end else if (ack_reply_sync != ack_reply_seen) begin
                ack_reply_seen <= ack_reply_sync;
                ack_ps_settle <= 2'd2;
            end
        end
    end

    // ADC domain: capture coherent snapshot on request. Guard ACK using the
    // current bank-generation identity (not just the bank number).
    // The actual sink consumes the registered adc_sw_ack_valid on the NEXT
    // ADC rising edge. Only then do we toggle reply to PS.
    always @(posedge adc_clk) begin
        if (!adc_resetn) begin
            status_req_meta <= 1'b0;
            status_req_sync <= 1'b0;
            ack_req_meta <= 1'b0;
            ack_req_sync <= 1'b0;
            status_req_seen <= 1'b0;
            ack_req_seen <= 1'b0;
            status_reply_toggle <= 1'b0;
            ack_reply_toggle <= 1'b0;
            status_ready_held <= 2'b00;
            status_seq0_held <= 32'd0;
            status_seq1_held <= 32'd0;
            status_count_held <= 32'd0;
            status_started_held <= 32'd0;
            status_replayed_held <= 32'd0;
            status_skipped_held <= 32'd0;
            status_idle_held <= 1'b0;
            status_run_held <= 1'b0;
            status_period_held <= 32'd0;
            ack_result_held <= 1'b0;
            adc_sw_ack_valid <= 1'b0;
            adc_sw_ack_bank <= 1'b0;
            adc_ack_finalize <= 1'b0;
        end else begin
            status_req_meta <= status_req_toggle;
            status_req_sync <= status_req_meta;
            ack_req_meta <= ack_req_toggle;
            ack_req_sync <= ack_req_meta;
            adc_sw_ack_valid <= 1'b0;

            if (status_req_sync != status_req_seen) begin
                status_req_seen <= status_req_sync;
                status_ready_held <= adc_frame_ready;
                status_seq0_held <= adc_bank0_sequence;
                status_seq1_held <= adc_bank1_sequence;
                status_count_held <= adc_completed_frames;
                status_started_held <= adc_captures_started;
                status_replayed_held <= adc_captures_replayed;
                status_skipped_held <= adc_skipped_windows;
                status_idle_held <= adc_scheduler_idle;
                status_run_held <= adc_run_enable;
                status_period_held <= adc_period_cycles;
                status_reply_toggle <= ~status_reply_toggle;
            end

            if (adc_ack_finalize) begin
                // Sink sees adc_sw_ack_valid from prior ADC cycle here.
                adc_ack_finalize <= 1'b0;
                ack_reply_toggle <= ~ack_reply_toggle;
            end else if (ack_req_sync != ack_req_seen) begin
                ack_req_seen <= ack_req_sync;
                if (adc_frame_ready[ack_bank_held] &&
                    ((ack_bank_held ? adc_bank1_sequence : adc_bank0_sequence)
                      == ack_seq_held)) begin
                    adc_sw_ack_valid <= 1'b1;
                    adc_sw_ack_bank <= ack_bank_held;
                    ack_result_held <= 1'b1;
                    adc_ack_finalize <= 1'b1;
                end else begin
                    ack_result_held <= 1'b0;
                    ack_reply_toggle <= ~ack_reply_toggle;
                end
            end
        end
    end

    // CAL9 runtime acquisition control.
    // Assumes coordinated assertion of both local resets.
    // PS holds command payload until acknowledged.

    reg capture_req_toggle;
    reg capture_reply_toggle;

    reg capture_enable_held;
    reg [31:0] capture_period_held;
    reg capture_result_held;

    (* ASYNC_REG = "TRUE", SHREG_EXTRACT = "NO" *)
    reg capture_req_meta, capture_req_sync;

    (* ASYNC_REG = "TRUE", SHREG_EXTRACT = "NO" *)
    reg capture_reply_meta, capture_reply_sync;

    reg capture_req_seen;
    reg capture_reply_seen;

    reg [1:0] capture_adc_settle;
    reg [1:0] capture_ps_settle;

    // PS clock domain.
    always @(posedge ps_clk) begin
        if (!ps_resetn) begin
            capture_req_toggle <= 1'b0;
            capture_enable_held <= 1'b0;
            capture_period_held <= 32'd0;

            capture_reply_meta <= 1'b0;
            capture_reply_sync <= 1'b0;
            capture_reply_seen <= 1'b0;
            capture_ps_settle <= 2'd0;

            ps_capture_busy <= 1'b0;
            ps_capture_done <= 1'b0;
            ps_capture_accepted <= 1'b0;
        end else begin
            capture_reply_meta <= capture_reply_toggle;
            capture_reply_sync <= capture_reply_meta;

            ps_capture_done <= 1'b0;

            if (!ps_capture_busy) begin
                if (ps_capture_req) begin
                    capture_enable_held <= ps_capture_enable;
                    capture_period_held <= ps_capture_period;

                    capture_req_toggle <= ~capture_req_toggle;

                    ps_capture_busy <= 1'b1;
                    ps_capture_accepted <= 1'b0;
                end
            end else if (capture_ps_settle != 0) begin
                capture_ps_settle <= capture_ps_settle - 1'b1;

                if (capture_ps_settle == 1) begin
                    ps_capture_accepted <= capture_result_held;
                    ps_capture_busy <= 1'b0;
                    ps_capture_done <= 1'b1;
                end
            end else if (
                capture_reply_sync != capture_reply_seen
            ) begin
                capture_reply_seen <= capture_reply_sync;
                capture_ps_settle <= 2'd2;
            end
        end
    end

    // ADC clock domain.
    always @(posedge adc_clk) begin
        if (!adc_resetn) begin
            capture_req_meta <= 1'b0;
            capture_req_sync <= 1'b0;
            capture_req_seen <= 1'b0;

            capture_adc_settle <= 2'd0;
            capture_reply_toggle <= 1'b0;
            capture_result_held <= 1'b0;

            adc_run_enable <= 1'b0;
            adc_period_cycles <= 32'd125000000;
        end else begin
            capture_req_meta <= capture_req_toggle;
            capture_req_sync <= capture_req_meta;

            if (capture_adc_settle != 0) begin
                capture_adc_settle <= capture_adc_settle - 1'b1;

                if (capture_adc_settle == 1) begin

                    // STOP: inhibit new captures.
                    // Do not reset or discard the in-flight frame.
                    if (!capture_enable_held) begin
                        adc_run_enable <= 1'b0;
                        capture_result_held <= 1'b1;

                    // START: accept only when stopped and drained.
                    end else if (
                        !adc_run_enable &&
                        adc_scheduler_idle &&
                        (adc_frame_ready == 2'b00) &&
                        (adc_captures_started ==
                         adc_captures_replayed) &&
                        (adc_captures_replayed ==
                         adc_completed_frames) &&
                        (capture_period_held >= 32'd12500) &&
                        (capture_period_held <= 32'd125000000)
                    ) begin
                        adc_period_cycles <= capture_period_held;
                        adc_run_enable <= 1'b1;
                        capture_result_held <= 1'b1;

                    end else begin
                        capture_result_held <= 1'b0;
                    end

                    capture_reply_toggle <= ~capture_reply_toggle;
                end

            end else if (
                capture_req_sync != capture_req_seen
            ) begin
                capture_req_seen <= capture_req_sync;
                capture_adc_settle <= 2'd2;
            end
        end
    end

endmodule
